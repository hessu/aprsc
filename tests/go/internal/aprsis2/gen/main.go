// Command gen regenerates the Go code for src/aprsis2.proto and records the
// hash of the schema it was generated from. Run it with go generate.
package main

import (
	"crypto/sha256"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
)

const goPackage = "github.com/hessu/aprsc/tests/go/internal/aprsis2"

func main() {
	// go generate runs in the directory of the package with the directive
	protoDir := filepath.Join("..", "..", "..", "..", "src")

	cmd := exec.Command("protoc",
		"--go_out=.",
		"--go_opt=paths=source_relative",
		"--go_opt=Maprsis2.proto="+goPackage,
		"-I", protoDir,
		"aprsis2.proto")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("protoc failed (are protoc and protoc-gen-go in PATH?): %v", err)
	}

	schema, err := os.ReadFile(filepath.Join(protoDir, "aprsis2.proto"))
	if err != nil {
		log.Fatal(err)
	}

	hash := fmt.Sprintf("%x", sha256.Sum256(schema))
	out := "// Code generated by go generate; DO NOT EDIT.\n\n" +
		"package aprsis2\n\n" +
		"// SchemaSHA256 is the hash of src/aprsis2.proto the Go code was generated from.\n" +
		"const SchemaSHA256 = \"" + hash + "\"\n"
	if err := os.WriteFile("schema_hash.go", []byte(out), 0o644); err != nil {
		log.Fatal(err)
	}
}
